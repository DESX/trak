import { chromium } from "playwright";
const base = "http://127.0.0.1:8766/viewer/";
const browser = await chromium.launch({ executablePath: process.env.TRAK_CHROMIUM });
const p = await browser.newPage({ viewport: { width: 1400, height: 860 } });
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await p.goto(`${base}#f=sophie-5gb.trak&v=${encodeURIComponent("table:sessions.8.turns@150000")}`);
await p.waitForSelector(".row");
await p.waitForTimeout(500);
await p.screenshot({ path: "out/table.png" });
await p.click(".h.group >> text=context");
await p.waitForTimeout(300);
await p.screenshot({ path: "out/table-expanded.png" });
await p.goto(`${base}#f=sophie-5gb.trak&v=${encodeURIComponent("tree:defaults@2000")}`);
await p.waitForSelector(".line");
await p.click(".line >> text=prompts");
await p.waitForTimeout(400);
await p.keyboard.press("ArrowDown");
await p.waitForTimeout(400);
await p.screenshot({ path: "out/defaults.png" });
await p.goto(`${base}#f=sophie-5gb.trak&v=${encodeURIComponent("items:sessions.8.turns@150000")}`);
await p.waitForSelector(".line.focus");
await p.waitForTimeout(300);
await p.screenshot({ path: "out/items.png" });
await p.goto(`${base}#f=sophie-5gb.trak&v=${encodeURIComponent("log:@1600000")}`);
await p.waitForSelector(".append");
await p.waitForTimeout(300);
await p.screenshot({ path: "out/log.png" });
console.log(errors.join("\n") || "no errors");
await browser.close();
